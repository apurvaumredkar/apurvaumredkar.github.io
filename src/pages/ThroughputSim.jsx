const REF_TFLOPS = 1979 // H200 SXM baseline for image gen scaling

// ─── Simulation engine ────────────────────────────────────────────────────────
function computeMetrics(gpu, numCards, workload) {
  const totalMemory    = gpu.memoryGb * numCards
  const totalBandwidth = gpu.bandwidthTBs * numCards
  const totalPower     = (gpu.tdpW * numCards) / 1000

  // ── Image generation (compute-bound, not bandwidth-bound) ──
  if (workload.isImageWorkload) {
    const imgsPerMinPerCard = (gpu.fp16Tflops / REF_TFLOPS) * workload.baseImgsPerMinPerCard
    const totalImgsPerMin   = Math.round(imgsPerMinPerCard * numCards)
    const imageLatencyMs    = Math.round(60000 / imgsPerMinPerCard)
    const memForJobs        = Math.max(0, totalMemory - workload.modelSizeGb)
    const concurrentUsers   = Math.floor(memForJobs / workload.kvPerSessionGb)
    return {
      totalMemoryGb: totalMemory, totalBandwidthTBs: totalBandwidth, totalPowerKw: totalPower,
      concurrentUsers, ttftMs: 0, generationMs: imageLatencyMs, e2eMs: imageLatencyMs,
      totalTps: totalImgsPerMin, modelTooLarge: false,
    }
  }

  // ── LLM workloads ──
  const scale = workload.modelSizeGb / 14  // 14 GB = 7B BF16 baseline

  // NVLink: tensor-parallel, memory pools
  if (gpu.interconnect === 'nvlink') {
    const availableKV   = Math.max(0, totalMemory - workload.modelSizeGb)
    const concurrentUsers = workload.kvPerSessionGb > 0
      ? Math.floor(availableKV / workload.kvPerSessionGb) : 999
    const adjTps        = (gpu.baseTpsPerCard / scale) * numCards
    const ttftMs        = Math.round((gpu.baseTtftMs * scale) / numCards * 1.15)
    const generationMs  = workload.avgResponseTokens > 0
      ? Math.round((workload.avgResponseTokens / adjTps) * 1000) : 0
    const e2eMs = workload.pipelinePreMs + ttftMs + generationMs + workload.pipelinePostMs
    return {
      totalMemoryGb: totalMemory, totalBandwidthTBs: totalBandwidth, totalPowerKw: totalPower,
      concurrentUsers, ttftMs, generationMs, e2eMs, totalTps: Math.round(adjTps), modelTooLarge: false,
    }
  }

  // PCIe: multi-instance, each card holds its own full model copy
  if (workload.modelSizeGb > gpu.memoryGb) {
    return {
      totalMemoryGb: totalMemory, totalBandwidthTBs: totalBandwidth, totalPowerKw: totalPower,
      concurrentUsers: 0, ttftMs: 0, generationMs: 0, e2eMs: 0, totalTps: 0, modelTooLarge: true,
    }
  }
  const perCardKV       = Math.max(0, gpu.memoryGb - workload.modelSizeGb)
  const perCardUsers    = workload.kvPerSessionGb > 0 ? Math.floor(perCardKV / workload.kvPerSessionGb) : 999
  const concurrentUsers = perCardUsers * numCards
  const adjTps          = gpu.baseTpsPerCard / scale
  const ttftMs          = Math.round(gpu.baseTtftMs * scale)
  const generationMs    = workload.avgResponseTokens > 0
    ? Math.round((workload.avgResponseTokens / adjTps) * 1000) : 0
  const e2eMs = workload.pipelinePreMs + ttftMs + generationMs + workload.pipelinePostMs
  return {
    totalMemoryGb: totalMemory, totalBandwidthTBs: totalBandwidth, totalPowerKw: totalPower,
    concurrentUsers, ttftMs, generationMs, e2eMs, totalTps: Math.round(adjTps), modelTooLarge: false,
  }
}


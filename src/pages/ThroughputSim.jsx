const KWH_RATE = 0.10  // $/kWh

function computeCosts(gpu, numCards, concurrentUsers) {
  const clusterCost    = gpu.priceUSD * numCards
  const annualPowerUSD = gpu.tdpW * numCards / 1000 * 8760 * KWH_RATE
  const monthlyPowerUSD = annualPowerUSD / 12
  const costPerUser    = concurrentUsers > 0 ? clusterCost / concurrentUsers : 0
  return { clusterCost, annualPowerUSD, monthlyPowerUSD, costPerUser }
}

function fmt$(n) {
  if (n >= 1_000_000) return `$${(n / 1_000_000).toFixed(2)}M`
  if (n >= 1_000)     return `$${Math.round(n / 1000)}K`
  return `$${Math.round(n)}`
}


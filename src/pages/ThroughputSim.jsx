function ScalingChart({ gpu, workload, accentClass }) {
  const maxVal = useMemo(() => {
    const vals = gpu.validCounts.map(n => computeMetrics(gpu, n, workload).concurrentUsers)
    return Math.max(...vals, 1)
  }, [gpu, workload])

  return (
    <div className="bg-white rounded-2xl border border-gray-100 shadow-sm p-5">
      <h3 className="text-sm font-medium text-gray-400 uppercase tracking-widest mb-4 font-[Montserrat,sans-serif]">
        Concurrent {gpu.validCounts.length > 1 ? workload.sessionNoun.charAt(0).toUpperCase() + workload.sessionNoun.slice(1) : 'Capacity'} vs Card Count
      </h3>
      <div className="flex items-end gap-2 h-32">
        {gpu.validCounts.map((n) => {
          const m = computeMetrics(gpu, n, workload)
          const h = (m.concurrentUsers / maxVal) * 100
          return (
            <div key={n} className="flex flex-col items-center gap-1 flex-1 min-w-0">
              <span className="text-sm font-semibold text-gray-700 truncate">{m.modelTooLarge ? '—' : m.concurrentUsers}</span>
              <motion.div layout className={`w-full rounded-t-lg opacity-80 ${accentClass || 'bg-[#0071e3]'}`}
                style={{ height: `${m.modelTooLarge ? 0 : h}%` }} transition={{ duration: 0.4 }} />
              <span className="text-sm text-gray-400">{n}×</span>
            </div>
          )
        })}
      </div>
    </div>
  )
}

